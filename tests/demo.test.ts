import { test } from 'node:test';
import assert from 'node:assert/strict';
import { demoRequest } from '../lib/demo.ts';
import type { Admin, Portal } from '../lib/types.ts';
const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (key: string) => storage.get(key) || null, setItem: (key: string, value: string) => storage.set(key, value) } });
Object.defineProperty(globalThis, 'location', { value: { origin: 'https://demo.example.org' } });

test('flujo demo completo: enlaces, permisos, revocación e historial', async () => {
  await demoRequest('reset');
  const matches = await demoRequest('matches', { name: 'Ana Garcia' }) as { name: string }[];
  assert.deepEqual(matches, [{ name: 'Ana García' }]);
  await assert.rejects(demoRequest('register', { name: 'Ana Garcia' }), /Confirma/);
  const registration = await demoRequest('register', { name: 'Ana Garcia', confirmDuplicate: true }) as { link: string };
  const oldToken = registration.link.split('#')[1];
  await demoRequest('wishlist', { wishlist: 'Un libro' });
  const before = await demoRequest('portal') as Portal;
  assert.equal(before.recipient, null);
  assert.equal(before.person.wishlist, 'Un libro');
  const id = before.person.id;
  await demoRequest('logout');
  await assert.rejects(demoRequest('portal'));
  await demoRequest('exchange', { token: oldToken });
  assert.equal((await demoRequest('portal') as Portal).person.id, id);
  await assert.rejects(demoRequest('admin/draw', { confirm: false }), /Confirma/);
  await demoRequest('admin/draw', { confirm: true });
  const portal = await demoRequest('portal') as Portal;
  assert.ok(portal.recipient);
  assert.notEqual(portal.recipient?.name, portal.person.name);
  assert.deepEqual(Object.keys(portal.recipient!).sort(), ['name', 'wishlist']);
  await assert.rejects(demoRequest('wishlist', { wishlist: 'Otro' }), /cerrada/);
  await demoRequest('admin/permission', { id, enabled: true });
  await demoRequest('wishlist', { wishlist: 'Edición excepcional' });
  const firstAdmin = await demoRequest('admin') as Admin;
  const firstDraw = await demoRequest('admin/history', { id: firstAdmin.draws[0].id });
  await demoRequest('admin/draw', { confirm: true });
  assert.deepEqual(await demoRequest('admin/history', { id: firstAdmin.draws[0].id }), firstDraw);
  assert.equal((await demoRequest('admin') as Admin).draws.length, 2);
  await demoRequest('admin/token', { id, action: 'revoke' });
  await assert.rejects(demoRequest('exchange', { token: oldToken }), /inválido/);
  await assert.rejects(demoRequest('wishlist', { wishlist: 'No' }), /revocado/);
  await assert.rejects(demoRequest('admin/token', { id, action: 'copy' }), /revocado/);
  const regenerated = await demoRequest('admin/token', { id, action: 'regenerate' }) as { link: string };
  assert.notEqual(regenerated.link, registration.link);
  await assert.rejects(demoRequest('exchange', { token: oldToken }), /inválido/);
  await assert.rejects(demoRequest('portal'), /regenerado/);
  await demoRequest('exchange', { token: regenerated.link.split('#')[1] });
  assert.equal((await demoRequest('portal') as Portal).person.id, id);
});
